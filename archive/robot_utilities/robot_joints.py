def get_row1_2_approach(col: str) -> list:
    """
    Return [top, bottom] joint positions for row1_2 of the given column.
    Used for both pick and dispose - robot travels Q_TRANSIT_2 -> top -> bottom.
    """
    row = _COLUMN_MAP[col.lower]["row1_2"]
    return [row["top"], row["bottom"]]


def get_row1_2_depart(col: str) -> list:
    """
    Return [bottom, top] joint positions for row1_2 of the given column.
    Used after the gripper action - robot travels bottom -> top -> Q_TRANSIT_2.
    """
    row = _COLUMN_MAP[col.lower]["row1_2"]
    return [row["bottom"], row["top"]]


def holding_area_row1_2_top(col: str) -> list:
    """Return the top (hover) joint position for row1_2 of the given column."""
    return _COLUMN_MAP[col.lower]["row1_2"]["top"]
