_COLUMN_MAP = {"a": _A, "b": _B, "c": _C, "d": _D}

# ---------------------------------------------------------------------------
# Core resolver
# ---------------------------------------------------------------------------

def _resolve(holding_pos: str) -> tuple:
    """
    Parse a holding area position ID (e.g. "a3") and return
    (row_dict, action_depth_key).
    """
    holding_pos = holding_pos.lower.strip
    if len(holding_pos) != 2:
        raise ValueError(f"Holding position must be 2 characters e.g. 'a3'. Got: '{holding_pos}'")

    col = holding_pos[0]
    pos = int(holding_pos[1])

    if col not in _COLUMN_MAP:
        raise ValueError(f"Unknown column '{col}'. Valid: a, b, c, d.")
    if pos not in POSITION_DEPTH:
        raise ValueError(f"Unknown position number '{pos}'. Valid: 1-5.")

    row_dict     = _COLUMN_MAP[col][_ROW_MAP[pos]]
    action_depth = POSITION_DEPTH[pos]
    return row_dict, action_depth

# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def holding_area_top(holding_pos: str) -> list:
    """
    Return the top (hover) joint position for a holding area position.
    Useful for using row3 tops as intermediate stepping waypoints.
    """
    row, _ = _resolve(holding_pos)
    return row["top"]


def get_approach_sequence(holding_pos: str) -> list:
    """
    Return [top, action_depth] - the two waypoints to descend into
    a holding area position.
    Call gripper action AFTER the last waypoint, then get_depart_sequence.
    """
    row, depth = _resolve(holding_pos)
    return [row["top"], row[depth]]


def get_depart_sequence(holding_pos: str) -> list:
    """
    Return [action_depth, top] - the two waypoints to ascend back out
    of a holding area position.
    Call this AFTER the gripper action.
    """
    row, depth = _resolve(holding_pos)
    return [row[depth], row["top"]]


def describe_holding_pos(holding_pos: str) -> str:
    """Human-readable description of a holding area position."""
    holding_pos = holding_pos.lower.strip
    col         = holding_pos[0].upper
    pos         = int(holding_pos[1])
    row_label   = _ROW_MAP[pos]
    depth       = POSITION_DEPTH[pos]
    return (f"Holding area {holding_pos.upper}: "
            f"column {col}, {row_label}, position {pos} -> depth '{depth}'")


